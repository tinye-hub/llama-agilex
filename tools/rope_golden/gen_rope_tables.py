CHUNK_WORDS = 2048  # keep each JVM <clinit> under 64 KiB bytecode


def _emit_array_chunks(lines, obj_prefix, words):
    n = len(words)
    chunk_count = (n + CHUNK_WORDS - 1) // CHUNK_WORDS
    for ci in range(chunk_count):
        start = ci * CHUNK_WORDS
        chunk = words[start : start + CHUNK_WORDS]
        lines.append(f"  private object {obj_prefix}{ci} {{")
        lines.append("    val words: Array[Int] = Array(")
        for row in range(0, len(chunk), 16):
            row_vals = ", ".join(str(w) for w in chunk[row : row + 16])
            lines.append(f"      {row_vals},")
        lines.append("    )")
        lines.append("  }")
        lines.append("")
    concat = " ++ ".join(f"{obj_prefix}{ci}.words" for ci in range(chunk_count))
    return concat


def emit_scala(cos_bits, sin_bits, out_path, max_pos, head_dim, theta):
    n = len(cos_bits)
    lines = [
        "// AUTO-GENERATED by tools/rope_golden/gen_rope_tables.py — do not edit.",
        "package rope",
        "",
        "/** Offline cos/sin tables for [[RoPECosSinRom]]. */",
        "object RoPETableInit {",
        f"  val maxPos: Int = {max_pos}",
        f"  val headDim: Int = {head_dim}",
        f"  val ropeTheta: Double = {theta}",
        f"  val wordCount: Int = {n}",
        "",
    ]
    cos_concat = _emit_array_chunks(lines, "CosChunk", cos_bits)
    sin_concat = _emit_array_chunks(lines, "SinChunk", sin_bits)
    lines += [
        f"  val cosBits: Array[Int] = {cos_concat}",
        f"  val sinBits: Array[Int] = {sin_concat}",
        "}",
        "",
    ]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out_path} ({n} words per table, chunk={CHUNK_WORDS})")


def emit_golden_txt(cos_bits, sin_bits, x_bits, pos, head_dim, out_dir):
    """Write questa-readable golden for one (pos, x[head_dim]) test vector."""
    x = [fp16_from_bits(b) for b in x_bits]
    cos_t = [fp16_from_bits(cos_bits[pos * head_dim + d]) for d in range(head_dim)]
    sin_t = [fp16_from_bits(sin_bits[pos * head_dim + d]) for d in range(head_dim)]
    y = []
    for i in range(head_dim // 2):
        x0, x1 = x[2 * i], x[2 * i + 1]
        c, s = cos_t[2 * i], sin_t[2 * i]
        y0 = fp16_from_bits(fp16_bits(x0 * c - x1 * s))
        y1 = fp16_from_bits(fp16_bits(x0 * s + x1 * c))
        y.append(y0)
        y.append(y1)
    out_dir.mkdir(parents=True, exist_ok=True)
    with (out_dir / "input_x.txt").open("w", encoding="utf-8") as f:
        for b in x_bits:
            f.write(f"{b:04x}\n")
    with (out_dir / "expected_y.txt").open("w", encoding="utf-8") as f:
        for v in y:
            f.write(f"{fp16_bits(v):04x}\n")
    with (out_dir / "meta.txt").open("w", encoding="utf-8") as f:
        f.write(f"pos={pos}\nhead_dim={head_dim}\n")


def main():
    ap = argparse.ArgumentParser(description="RoPE cos/sin table + golden generator")
    ap.add_argument("--max-pos", type=int, default=1024)
    ap.add_argument("--head-dim", type=int, default=64)
    ap.add_argument("--theta", type=float, default=500_000.0)
    ap.add_argument("--scala-out", type=Path,
                    default=Path("src/scala/rope/scala/RoPETableInit.scala"))
    ap.add_argument("--golden-dir", type=Path, default=None,
                    help="If set, write fixed TB golden vectors under this directory")
    args = ap.parse_args()

    cos_bits, sin_bits = precompute_cos_sin(args.max_pos, args.head_dim, args.theta)
    emit_scala(cos_bits, sin_bits, args.scala_out, args.max_pos, args.head_dim, args.theta)

    if args.golden_dir is not None:
        # Deterministic small vector: x[d] = (d - 32) in fp16-ish pattern
        x_bits = [fp16_bits(float((d % 17) - 8)) for d in range(args.head_dim)]
        emit_golden_txt(cos_bits, sin_bits, x_bits, pos=3, head_dim=args.head_dim,
                        out_dir=args.golden_dir)


if __name__ == "__main__":
    main()
