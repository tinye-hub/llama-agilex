#!/usr/bin/env python3
"""Generate RoPE cos/sin FP16 tables and optional golden vectors for Questa."""

import argparse
import math
import struct
from pathlib import Path


def fp16_bits(f):
    return struct.unpack("<H", struct.pack("<e", f))[0]


def fp16_from_bits(b):
    return struct.unpack("<e", struct.pack("<H", b & 0xFFFF))[0]


def precompute_cos_sin(max_pos, head_dim, theta):
    """Return (cos_bits, sin_bits) flat arrays of length max_pos * head_dim."""
    assert head_dim % 2 == 0
    cos_out = []
    sin_out = []
    inv_freq = [1.0 / (theta ** (2 * i / head_dim)) for i in range(head_dim // 2)]
    for pos in range(max_pos):
        for d in range(head_dim):
            pair = d // 2
            angle = pos * inv_freq[pair]
            c = math.cos(angle)
            s = math.sin(angle)
            cos_out.append(fp16_bits(c))
            sin_out.append(fp16_bits(s))
    return cos_out, sin_out


def roperotate_ref(x, cos_t, sin_t):
    """Software model of llama-fpga RoPERotate + out = x*cos + rot*sin."""
    dim = len(x)
    half = dim // 2
    bypass: list[float] = []
    rotate_fifo: list[float] = []
    out: list[float] = [0.0] * dim
    input_second_half = False
    rotate_second_half = False
    rotate_fifo_pop_idx = 0

    def neg_swap(v: float) -> float:
        # Bits: ~sign_bit | lower bits  (FP16 negation via sign flip)
        b = fp16_bits(v)
        nb = (b ^ 0x8000) & 0xFFFF
        return fp16_from_bits(nb)

    for d in range(dim):
        xv = x[d]
        if not input_second_half:
            bypass.append(xv)
            rotate_fifo.append(xv)
        else:
            in2rot = neg_swap(xv)
            if rotate_second_half:
                rot_v = rotate_fifo[rotate_fifo_pop_idx]
                rotate_fifo_pop_idx += 1
            else:
                rot_v = in2rot
