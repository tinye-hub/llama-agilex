        # Re-run with explicit fifo pops matching RTL
    # Clear and redo with explicit state machine matching RTL
    bypass_q: list[float] = []
    rot_q: list[float] = []
    in_sh = False
    rot_sh = False
    rot_cnt = 0
    bypass_pop = 0
    rot_pop = 0
    results: list[float] = []
    for d in range(dim):
        xv = x[d]
        in2rot = neg_swap(xv)
        if not in_sh:
            bypass_q.append(xv)
            rot_q.append(xv)
        if in_sh:
            if rot_sh:
                rot_v = rot_q[rot_pop]
                rot_pop += 1
            else:
                rot_v = in2rot
            byp_v = bypass_q[bypass_pop]
            bypass_pop += 1
